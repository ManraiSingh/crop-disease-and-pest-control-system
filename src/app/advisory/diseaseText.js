const BY_LANG = { hi: HI, mr: MR }

/**
 * The disease as it should be shown and spoken in the active language.
 * Falls back to the English entry when a language has no translation.
 */
export function diseaseText(cropKey, disease, language) {
  const entry = BY_LANG[language]?.[cropKey]?.[disease.name]
  if (!entry) return { name: disease.name, signs: disease.signs, action: disease.action }
  return entry
}
